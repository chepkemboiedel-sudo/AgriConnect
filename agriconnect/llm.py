"""Answer generation that adapts to whichever provider is available.

- If OPENAI_API_KEY is set, the answer is generated by the model but
  constrained to the retrieved sources (grounding enforced in the prompt).
- Otherwise, a dependency-free *extractive* answer is returned: it quotes the
  best supporting sentences from the retrieved chunks and cites them.

Both paths cite sources and never answer beyond the provided evidence, which
is exactly the behaviour the proposal commits to measuring.
"""
from __future__ import annotations
import re
from typing import Optional

from . import config
from .retrieval import tokenize

_SENT_RE = re.compile(r"(?<=[.!?])\s+")


def _extractive_answer(question: str, sources: list[dict]) -> str:
    """Pick the most relevant sentence(s) from the top sources and cite them.

    Overlap is measured on meaningful (stemmed, stop-worded) terms, and
    sentences from higher-ranked sources are preferred, so an incidental common
    word in a lower-ranked source cannot hijack the answer.
    """
    q = set(tokenize(question))
    best: list[tuple[float, str, str]] = []  # (score, sentence, title)
    for rank, src in enumerate(sources):
        for sent in _SENT_RE.split(src["text"].strip()):
            sent = sent.strip()
            if len(sent) < 15:
                continue
            overlap = len(q & set(tokenize(sent)))
            score = overlap - rank * 0.5  # prefer the top-ranked source
            best.append((score, sent, src["title"]))
    best.sort(key=lambda x: x[0], reverse=True)
    picked = [b for b in best if b[0] > 0][:2]
    if not picked:
        # fall back to the opening of the top source
        top = sources[0]
        first = _SENT_RE.split(top["text"].strip())[0]
        return f"{first} (Source: {top['title']})"
    parts = [f"{sent} (Source: {title})" for _, sent, title in picked]
    return " ".join(parts)


def _openai_answer(question: str, sources: list[dict]) -> Optional[str]:
    try:
        from openai import OpenAI
    except Exception:
        return None
    try:
        client = OpenAI(api_key=config.OPENAI_API_KEY)
        context = "\n\n".join(
            f"[{i+1}] {s['title']}\n{s['text']}" for i, s in enumerate(sources)
        )
        system = (
            "You are AgriConnect, a support assistant for an agricultural input "
            "supplier. Answer the customer ONLY using the numbered sources below. "
            "Cite sources inline like [1]. If the sources do not contain the "
            "answer, reply exactly: INSUFFICIENT_EVIDENCE. Keep it to 2-3 sentences."
        )
        resp = client.chat.completions.create(
            model=config.CHAT_MODEL,
            temperature=0,
            messages=[
                {"role": "system", "content": system},
                {"role": "user", "content": f"Sources:\n{context}\n\nQuestion: {question}"},
            ],
        )
        return resp.choices[0].message.content.strip()
    except Exception as exc:  # network/key/quota problems -> fall back gracefully
        print(f"[llm] OpenAI call failed, using local answer: {exc}")
        return None


def grounded_answer(question: str, sources: list[dict]) -> dict:
    """Return {text, provider, insufficient}.

    ``insufficient`` is True when even the model could not answer from the
    sources, so the agent should abstain and hand off.
    """
    if config.PROVIDER == "openai":
        ans = _openai_answer(question, sources)
        if ans is not None:
            insufficient = "INSUFFICIENT_EVIDENCE" in ans
            return {"text": ans, "provider": "openai", "insufficient": insufficient}
    # local / fallback
    return {"text": _extractive_answer(question, sources),
            "provider": "local", "insufficient": False}
